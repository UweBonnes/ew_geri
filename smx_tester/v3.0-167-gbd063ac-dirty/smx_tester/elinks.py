import logging as log

from hctsp import *

import agwb

class Elinks:
    """Class representing elinks block."""

    def __init__(self, handle):
        """
        Parameters
        ----------
        handle
            Handle to the instance of the elinks object generated by the agwb.
        """
        self.handle = handle

    def set_downlink_mask(self, mask):
        log.debug("Setting downlink mask: {:05b}".format(mask))
        self.handle.downlink_mask.write(mask)

    def disable_downlink_clock(self, clock, downlinks = None):
        assert 0 <= clock <= agwb.N_HCTSP_DOWNLINKS
        if downlinks is None:
            downlinks = [clock,]
        for downlink in downlinks:
            assert 0 <= downlink <= agwb.N_HCTSP_DOWNLINKS
        downlink_mask = self.handle.downlink_mask.read()
        for downlink in downlinks:
            log.info("Disabling clock on downlink {}".format(downlink))
            downlink_mask |= 1 << downlink
        self.set_downlink_mask(downlink_mask)
        clocks_ena = self.handle.elink_clk_ena.read()
        clocks_ena |= 1 << clock
        clocks_ena ^= 1 << clock
        self.handle.elink_clk_ena.write(clocks_ena)

    def set_downlink_clock(self, clock, freq, phase, downlinks = None):
        """Set the frequency and phase of the E-Links clock.

        Parameters
        ----------
        clock: int
            Clock nr from 0 to agwb.N_HCTSP_DOWNLINKS
        freq: int
            CLK_40, CLK_80 or CLK_160
        phase : int
            Phase value in range from 0 to 511.
        downlinks:
            List of associated downlinks. If not given, 
            set to a single downlink with the same number
            as clock.
        """
        assert 0 <= clock <= agwb.N_HCTSP_DOWNLINKS
        if downlinks is None:
            downlinks = [clock,]
        for downlink in downlinks:
            assert 0 <= downlink <= agwb.N_HCTSP_DOWNLINKS
        assert CLK_40 <= freq <= CLK_160
        assert (phase >= 0) and (phase < 512)

        # VCO frequency = 1600 MHz, resolution = 1/8 VCO period.
        phase_ns = phase * 1 / (8 * 1600e6) * 1e9

        log.debug("Setting clock on downlink {}: freq: {}, phase: {} ({:.3f} ns)".format(downlink, freq, phase, phase_ns))

        downlink_mask = self.handle.downlink_mask.read()
        for downlink in downlinks:
            downlink_mask |= 1 << downlink
        self.set_downlink_mask(downlink_mask)

        ctrl = (phase << 5) | (freq << 3) | downlink
        self.handle.clk_ctrl.write(ctrl)

        while self.handle.clk_stat.delay_ready.readf() == 0:
            pass
        log.debug("Waiting for Elinks PLL lock")
        while self.handle.clk_stat.pll_locked.readf() == 0:
            pass
        clocks_ena = self.handle.elink_clk_ena.read()
        clocks_ena |= 1 << clock
        self.handle.elink_clk_ena.write(clocks_ena)

        for downlink in downlinks:
            downlink_mask |= 1 << downlink
            downlink_mask ^= 1 << downlink
        self.set_downlink_mask(downlink_mask)

    def set_data_delay(self, uplink, bit_select, delay):
        """Set delay of data for uplink.

        Parameters
        ----------
        uplink : int
            Uplink number.
        bit_select : int
            Bit select. Data is always sampled with 320 MHz and DDR.
        delay : int
            Delay value in range from 0 to 31.
        """
        assert (uplink >= 0) and (uplink < agwb.N_HCTSP_UPLINKS)
        assert (delay >= 0) and (delay < 32)

        log.debug("Setting data delay - uplink {}, bit select {}, delay {}.".format(uplink, bit_select, delay))

        self.handle.din_ctrl[uplink].bit_select.writef(bit_select)
        self.handle.din_ctrl[uplink].delay.writef(delay)
        while self.handle.din_stat[uplink].delay_ready.readf() == 0:
            pass

